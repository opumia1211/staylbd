/**
 * One-time / maintenance: split monolithic main.css into route-targeted chunks.
 * Run from core/:  node tools/split-main-legacy-css.cjs
 *
 * After editing public/assets/templates/basic/css/main.css, re-run to refresh chunks,
 * or edit the chunk files directly (main.css should stay as @import composer only).
 */
const fs = require('fs');
const path = require('path');

const mainPath = path.join(__dirname, '../public/assets/templates/basic/css/main.css');
const outDir = path.join(__dirname, '../public/assets/templates/basic/css');

const banner = `/* Generated by tools/split-main-legacy-css.cjs — run: npm run split:main-css */\n`;

const ranges = [
    { file: 'main-legacy-shell.css', start: 1, end: 1869 },
    { file: 'main-legacy-home.css', start: 1870, end: 5025 },
    { file: 'main-legacy-product.css', start: 5026, end: 8280 },
    { file: 'main-legacy-extras.css', start: 8282, end: 8672 },
    { file: 'main-legacy-classic.css', start: 8673, end: 12850 },
    { file: 'main-legacy-widgets.css', start: 12855, end: 13677 },
];

const raw = fs.readFileSync(mainPath, 'utf8');
if (raw.includes('@import "./main-legacy-')) {
    console.error(
        'main.css is the @import composer. Restore the monolithic main.css from version control, then run npm run split:main-css.'
    );
    process.exit(1);
}
const lines = raw.split(/\r?\n/);

function sliceLines(a, b) {
    return lines.slice(a - 1, b).join('\n') + '\n';
}

for (const { file, start, end } of ranges) {
    const body = sliceLines(start, end);
    fs.writeFileSync(path.join(outDir, file), banner + body, 'utf8');
    console.log('Wrote', file, `(${start}-${end}, ${body.length} bytes)`);
}

const composer = `${banner}/* Composer: full stack. Mix uses main-legacy-*.css directly per route. */
@import "./main-legacy-shell.css";
@import "./main-legacy-home.css";
@import "./main-legacy-product.css";
@import "./main-legacy-extras.css";
@import "./main-legacy-classic.css";
@import "./main-legacy-widgets.css";
`;

fs.writeFileSync(mainPath, composer, 'utf8');
console.log('Rewrote main.css as @import composer (monolith replaced).');
